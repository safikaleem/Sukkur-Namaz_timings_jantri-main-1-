/// Ahmiyat-e-Ramzan chapters/index dataset with comprehensive support for all 10 app languages.
class AhmiyatRamzanTopic {
  final int num;
  final int page;
  final Map<String, String> titles;
  final Map<String, String> authors;

  const AhmiyatRamzanTopic({
    required this.num,
    required this.page,
    required this.titles,
    required this.authors,
  });

  String getTitle(String languageCode) {
    return titles[languageCode] ?? titles['urdu'] ?? titles['english'] ?? '';
  }

  String getAuthor(String languageCode) {
    return authors[languageCode] ?? authors['urdu'] ?? authors['english'] ?? '';
  }
}

